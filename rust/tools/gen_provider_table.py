#!/usr/bin/env python3
"""Generates rust/crates/nyan-coding-agent-models/src/table.rs.

Source of truth: packages/ai/src/providers/*.ts (id, name, baseUrl),
packages/ai/src/env-api-keys.ts (API-key variables), and the hydrated model
data in packages/ai/src/providers/data/*.json (which wire API each model uses).
Run `npm run hydrate:model-data` first, then:

    python3 rust/tools/gen_provider_table.py
"""
import collections, glob, json, os, re, subprocess, sys

root = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
providers = os.path.join(root, "packages/ai/src/providers")
env_src = open(os.path.join(root, "packages/ai/src/env-api-keys.ts")).read()
env_map = dict(re.findall(r'^\s*"?([a-z0-9-]+)"?: "([A-Z0-9_]+)",?$', env_src, flags=re.M))
commit = subprocess.check_output(["git", "rev-parse", "--short", "HEAD"], cwd=root, text=True).strip()

API = {
    "openai-completions": "OpenAiCompletions",
    "openai-responses": "OpenAiResponses",
    "azure-openai-responses": "AzureOpenAiResponses",
    "anthropic-messages": "AnthropicMessages",
    "google-generative-ai": "GoogleGenerativeAi",
    "google-vertex": "GoogleVertex",
    "mistral-conversations": "MistralConversations",
    "bedrock-converse-stream": "BedrockConverse",
}
NON_CHAT = {
    "openai-decisions", "typesafe-system-one", "openrouter-images",
    "cloudflare-workers-ai-system-one", "llama-cpp-classify",
}
supported, mixed, other = [], [], []
for path in sorted(glob.glob(os.path.join(providers, "data", "*.json"))):
    pid = os.path.basename(path)[:-5]
    data = json.load(open(path))
    combos = collections.Counter()
    for api, models in data.items():
        for model in models.values():
            combos[(model.get("api", api), model.get("baseUrl"))] += 1
    ts_path = os.path.join(providers, f"{pid}.ts")
    ts = open(ts_path).read() if os.path.exists(ts_path) else ""
    name = (re.search(r'id:\s*"%s",\s*name:\s*"([^"]+)"' % re.escape(pid), ts) or [None, pid])[1]
    base = (re.search(r'baseUrl:\s*"([^"]+)"', ts) or [None, None])[1]
    # Classifier and image models are not chat models; they never reach the agent loop.
    apis = {api for api, _ in combos} - NON_CHAT
    envs = [env_map[pid]] if pid in env_map else []
    if len(apis) > 1:
        mixed.append((pid, name, envs))
    elif not apis:
        other.append((pid, ["(no chat models)"]))
    elif apis <= set(API):
        api = next(iter(apis))
        urls = {url for api_name, url in combos if api_name not in NON_CHAT}
        url = base or (next(iter(urls)) if len(urls) == 1 else None)
        supported.append((pid, name, API[api], url, envs))
    else:
        other.append((pid, sorted(apis)))

out = [
    "//! Generated by `rust/tools/gen_provider_table.py`; do not edit by hand.",
    f"//! Source: packages/ai/src/providers at {commit}.",
    "",
    "#![cfg_attr(rustfmt, rustfmt::skip)]",
    "#![allow(clippy::enum_glob_use)]",
    "",
    "use crate::WireApi::{self, *};",
    "",
    "/// A provider that uses one wire API for all of its models.",
    "#[derive(Debug)]",
    "pub struct ProviderDef {",
    "    /// Provider id.",
    "    pub id: &'static str,",
    "    /// Display name.",
    "    pub name: &'static str,",
    "    /// The wire API every model of the provider uses.",
    "    pub api: WireApi,",
    "    /// The fixed base URL, when the provider has one.",
    "    pub base_url: Option<&'static str>,",
    "    /// Environment variables that can hold the API key, strongest first.",
    "    pub env_keys: &'static [&'static str],",
    "}",
    "",
    "/// Providers with a single wire API.",
    "pub const PROVIDERS: &[ProviderDef] = &[",
]
for pid, name, api, url, envs in supported:
    url_text = f'Some("{url}")' if url else "None"
    env_text = ", ".join(f'"{e}"' for e in envs)
    out.append(f'    ProviderDef {{ id: "{pid}", name: "{name}", api: {api}, base_url: {url_text}, env_keys: &[{env_text}] }},')
out += [
    "];",
    "",
    "/// A provider whose models use different wire APIs; the API comes from the model catalog.",
    "#[derive(Debug)]",
    "pub struct MixedDef {",
    "    /// Provider id.",
    "    pub id: &'static str,",
    "    /// Display name.",
    "    pub name: &'static str,",
    "    /// Environment variables that can hold the API key, strongest first.",
    "    pub env_keys: &'static [&'static str],",
    "}",
    "",
    "/// Providers whose models use different wire APIs.",
    "pub const MIXED_API_PROVIDERS: &[MixedDef] = &[",
]
for pid, name, envs in mixed:
    env_text = ", ".join(f'"{e}"' for e in envs)
    out.append(f'    MixedDef {{ id: "{pid}", name: "{name}", env_keys: &[{env_text}] }},')
out += ["];", "", "/// Providers whose wire API this build does not implement.", "pub const UNSUPPORTED_API_PROVIDERS: &[(&str, &str)] = &["]
out += [f'    ("{pid}", "{apis[0]}"),' for pid, apis in other]
out += ["];", ""]
dest = os.path.join(root, "rust/crates/nyan-coding-agent-models/src/table.rs")
open(dest, "w").write("\n".join(out))
print(f"{len(supported)} single-API, {len(mixed)} mixed, {len(other)} unsupported -> {dest}")
