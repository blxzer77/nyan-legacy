    struct ImmediateStream {
        events: VecDeque<ProviderStreamEvent>,
        fail_first: bool,
    }

    impl ProviderStream for ImmediateStream {
        fn next(&mut self) -> BoxFuture<Result<Option<ProviderStreamEvent>, ProviderError>> {
            if self.fail_first {
                self.fail_first = false;
                return Box::pin(async {
                    Err(ProviderError::Stream {
                        message: "temporary stream failure".to_owned(),
                        retryable: true,
                    })
                });
            }
            let event = self.events.pop_front();
            Box::pin(async move { Ok(event) })
        }
    }

    struct FakeProvider {
        responses: Mutex<VecDeque<Vec<ProviderStreamEvent>>>,
        failures: Mutex<usize>,
    }

    impl ModelProvider for FakeProvider {
        fn id(&self) -> &'static str {
            "fake"
        }

        fn stream(
            &self,
            _request: ProviderRequest,
        ) -> BoxFuture<Result<Box<dyn ProviderStream>, ProviderError>> {
            let failure = {
                let mut failures = self.failures.lock().expect("failure lock");
                if *failures > 0 {
                    *failures -= 1;
                    true
                } else {
                    false
                }
            };
            let response = self.responses.lock().expect("response lock").pop_front();
            Box::pin(async move {
                if failure {
                    return Err(ProviderError::Request {
                        message: "temporary provider failure".to_owned(),
                        retryable: true,
                        retry_after: None,
                    });
                }
                Ok(Box::new(ImmediateStream {
                    events: response
                        .unwrap_or_else(|| {
                            vec![
                                ProviderStreamEvent::TextDelta {
                                    text: "fallback".to_owned(),
                                },
                                ProviderStreamEvent::Finished {
                                    reason: ProviderStopReason::Stop,
                                },
                            ]
                        })
                        .into(),
                    fail_first: false,
                }) as Box<dyn ProviderStream>)
            })
        }
    }

