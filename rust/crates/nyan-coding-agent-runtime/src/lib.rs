//! Single-agent runtime primitives for the Rust Coding Agent.
//!
//! The runtime owns turn ordering and terminal outcomes, while providers and tools
//! own their external effects. It does not select an async executor.

#![forbid(unsafe_code)]

use std::fmt::{Display, Formatter};
use std::future::Future;
use std::path::PathBuf;
use std::pin::Pin;
use std::sync::{Arc, Mutex};
use std::task::{Context, Poll};

use nyan_coding_agent_core::{
    BoxFuture, CancellationToken, CoreError, ExecutionContext, Message, MessageRole, StopReason,
    ToolCall, ToolCallId, ToolResult, ToolUpdateSink,
};
use nyan_coding_agent_provider::{
    ProviderError, ProviderModel, ProviderRegistry, ProviderRequest, ProviderStopReason,
    ProviderStreamEvent, ToolSpec,
};
use nyan_coding_agent_session::{NativeSession, SessionRecordKind, SessionStoreError};
use nyan_coding_agent_tools::{ToolError, ToolRegistry};

/// Events emitted in deterministic order by one agent run.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum AgentEvent {
    /// The run has started.
    AgentStart,
    /// The run has reached a terminal outcome.
    AgentEnd {
        /// Terminal run outcome.
        outcome: AgentOutcome,
        /// Messages generated by this run, starting with the prompt.
        messages: Vec<Message>,
    },
    /// A provider turn has started.
    TurnStart {
        /// One-based turn number.
        turn: usize,
    },
    /// A message has begun.
    MessageStart {
        /// Initial message value.
        message: Message,
    },
    /// A streaming message changed.
    MessageUpdate {
        /// Current message value.
        message: Message,
        /// The content-block change that caused this update.
        event: AssistantEvent,
    },
    /// A message has finished.
    MessageEnd {
        /// Final message value.
        message: Message,
    },
    /// A retryable provider failure is being retried.
    RetryStart {
        /// One-based retry number.
        attempt: usize,
    },
    /// A provider retry attempt has ended.
    RetryEnd {
        /// One-based retry number.
        attempt: usize,
        /// Whether the retry produced a complete stream.
        succeeded: bool,
    },
    /// A tool call has begun.
    ToolExecutionStart {
        /// Provider call id.
        call_id: ToolCallId,
        /// Registered tool name.
        tool_name: String,
        /// Opaque JSON arguments.
        arguments: String,
    },
    /// A tool has emitted a partial result.
    ToolExecutionUpdate {
        /// Provider call id.
        call_id: ToolCallId,
        /// Registered tool name.
        tool_name: String,
        /// Partial result.
        partial_result: ToolResult,
    },
    /// A tool call has finished.
    ToolExecutionEnd {
        /// Provider call id.
        call_id: ToolCallId,
        /// Registered tool name.
        tool_name: String,
        /// Model-facing result.
        result: Message,
    },
    /// A turn has finished, including its tool results.
    TurnEnd {
        /// Assistant message for the turn.
        message: Message,
        /// Tool result messages generated by the turn.
        tool_results: Vec<Message>,
    },
}

/// One content-block change inside a streaming assistant message.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum AssistantEvent {
    /// A text block started.
    TextStart {
        /// Index of the block in the message content.
        content_index: usize,
    },
    /// Text was appended to a block.
    TextDelta {
        /// Index of the block in the message content.
        content_index: usize,
        /// The appended text.
        delta: String,
    },
    /// A text block ended with its authoritative content.
    TextEnd {
        /// Index of the block in the message content.
        content_index: usize,
        /// The complete block text.
        content: String,
    },
    /// A tool-call block started.
    ToolCallStart {
        /// Index of the block in the message content.
        content_index: usize,
        /// Provider call id.
        id: ToolCallId,
        /// Tool name.
        name: String,
    },
    /// A tool-call block ended with the complete call.
    ToolCallEnd {
        /// Index of the block in the message content.
        content_index: usize,
        /// The complete tool call.
        tool_call: ToolCall,
    },
}

/// Terminal state of a run.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum AgentOutcome {
    /// The provider completed without more tool calls.
    Completed,
    /// The owning process requested cancellation before an external effect started.
    Aborted,
    /// An external effect started but its final outcome could not be proven.
    Unknown {
        /// The operation whose outcome is not known.
        operation: String,
        /// Diagnostic explaining the uncertainty.
        message: String,
    },
    /// The run stopped on a stable runtime error.
    Failed {
        /// Stable error category.
        code: &'static str,
        /// User- or model-facing diagnostic.
        message: String,
    },
}

/// Final result and transcript returned by one run.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AgentRunResult {
    /// Messages appended during the run, including the prompt.
    pub messages: Vec<Message>,
    /// Stable terminal outcome.
    pub outcome: AgentOutcome,
}

/// Tool scheduling policy for one assistant message.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ToolExecutionMode {
    /// Execute tool calls in provider order.
    Sequential,
    /// Start all tool calls in one assistant message and await them concurrently.
    Parallel,
}

/// Configuration for one runtime instance.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct RuntimeConfig {
    /// Selected provider and model.
    pub model: ProviderModel,
    /// Working directory passed to tools.
    pub cwd: PathBuf,
    /// Maximum assistant turns, including the first request.
    pub max_turns: usize,
    /// Maximum fresh provider attempts after a retryable failure.
    pub max_retries: usize,
    /// Tool scheduling policy.
    pub tool_execution: ToolExecutionMode,
}

impl RuntimeConfig {
    /// Creates the default configuration for a terminal run.
    #[must_use]
    pub fn new(model: ProviderModel, cwd: impl Into<PathBuf>) -> Self {
        Self {
            model,
            cwd: cwd.into(),
            max_turns: 64,
            max_retries: 2,
            tool_execution: ToolExecutionMode::Parallel,
        }
    }
}

/// A transcript owned by the runtime.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct AgentContext {
    /// Messages visible to the provider in order.
    pub messages: Vec<Message>,
}

/// Errors raised internally before a stable terminal outcome is produced.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum RuntimeError {
    /// A shared core contract failed.
    Core(CoreError),
    /// The provider failed.
    Provider(ProviderError),
    /// A tool failed.
    Tool(ToolError),
    /// A tool effect started but its final outcome is unknown.
    UnknownOutcome {
        /// The operation whose outcome is not known.
        operation: String,
        /// Diagnostic explaining the uncertainty.
        message: String,
    },
    /// The configured turn budget was exhausted.
    TurnLimit {
        /// Configured maximum.
        max_turns: usize,
    },
    /// The provider ended without a terminal stream event.
    UnterminatedProviderStream,
}

struct StreamAttemptError {
    error: RuntimeError,
    emitted: bool,
}

impl StreamAttemptError {
    fn is_retryable(&self) -> bool {
        !self.emitted
            && matches!(
                &self.error,
                RuntimeError::Provider(error) if error.is_retryable()
            )
    }
}

impl RuntimeError {
    fn code(&self) -> &'static str {
        match self {
            Self::Core(error) => match error {
                CoreError::InvalidIdentifier { .. } => "invalid_identifier",
                CoreError::Cancelled => "cancelled",
                CoreError::Unsupported { .. } => "unsupported",
                CoreError::InvalidState { .. } => "invalid_state",
            },
            Self::Provider(error) => match error {
                ProviderError::Authentication { .. } => "auth",
                ProviderError::ModelUnavailable { .. } => "model",
                ProviderError::Request { .. } => "provider",
                ProviderError::Stream { .. } => "stream",
                ProviderError::Cancelled => "cancelled",
            },
            Self::Tool(_) => "tool",
            Self::UnknownOutcome { .. } => "unknown_outcome",
            Self::TurnLimit { .. } => "turn_limit",
            Self::UnterminatedProviderStream => "stream",
        }
    }

    fn is_cancelled(&self) -> bool {
        matches!(
            self,
            Self::Core(CoreError::Cancelled) | Self::Provider(ProviderError::Cancelled)
        )
    }
}

impl Display for RuntimeError {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Core(error) => error.fmt(formatter),
            Self::Provider(error) => error.fmt(formatter),
            Self::Tool(error) => error.fmt(formatter),
            Self::UnknownOutcome { operation, message } => {
                write!(
                    formatter,
                    "tool operation {operation} has unknown outcome: {message}"
                )
            }
            Self::TurnLimit { max_turns } => {
                write!(formatter, "agent turn limit reached: {max_turns}")
            }
            Self::UnterminatedProviderStream => {
                formatter.write_str("provider stream ended without a terminal event")
            }
        }
    }
}

impl std::error::Error for RuntimeError {}

impl From<CoreError> for RuntimeError {
    fn from(error: CoreError) -> Self {
        Self::Core(error)
    }
}

impl From<ProviderError> for RuntimeError {
    fn from(error: ProviderError) -> Self {
        Self::Provider(error)
    }
}

impl From<ToolError> for RuntimeError {
    fn from(error: ToolError) -> Self {
        match error {
            ToolError::UnknownOutcome { operation, message } => {
                Self::UnknownOutcome { operation, message }
            }
            other => Self::Tool(other),
        }
    }
}

/// Consumer of runtime events.
///
/// The shared receiver form lets a tool report partial results while its owned
/// future is still running. Implementations must serialize their own output if
/// they expose events to multiple threads.
pub trait EventSink: Send + Sync {
    /// Receives one event in run order.
    fn emit(&self, event: AgentEvent);
}

impl<F> EventSink for F
where
    F: Fn(AgentEvent) + Send + Sync,
{
    fn emit(&self, event: AgentEvent) {
        self(event);
    }
}

struct PendingTool {
    call: ToolCall,
    future: BoxFuture<Result<ToolResult, ToolError>>,
}

struct JoinToolFutures {
    pending: Vec<Option<PendingTool>>,
    results: Vec<Option<(ToolCall, Result<ToolResult, ToolError>)>>,
}

impl Future for JoinToolFutures {
    type Output = Vec<(ToolCall, Result<ToolResult, ToolError>)>;

    fn poll(self: Pin<&mut Self>, context: &mut Context<'_>) -> Poll<Self::Output> {
        let this = self.get_mut();
        let mut all_ready = true;
        for index in 0..this.pending.len() {
            let Some(pending) = this.pending[index].as_mut() else {
                continue;
            };
            match pending.future.as_mut().poll(context) {
                Poll::Ready(result) => {
                    let call = pending.call.clone();
                    this.results[index] = Some((call, result));
                    this.pending[index] = None;
                }
                Poll::Pending => all_ready = false,
            }
        }
        if all_ready {
            Poll::Ready(
                this.results
                    .iter_mut()
                    .map(Option::take)
                    .collect::<Option<Vec<_>>>()
                    .expect("every pending tool has a result when the join is ready"),
            )
        } else {
            Poll::Pending
        }
    }
}

/// Event sink that commits every finished message to a Rust-native session
/// journal before forwarding the event.
///
/// The first persistence failure is retained and later events are still
/// forwarded, so the caller can report the run outcome and the persistence
/// failure together instead of silently losing either.
pub struct SessionRecorder {
    session: Arc<Mutex<NativeSession>>,
    inner: Arc<dyn EventSink>,
    failure: Mutex<Option<SessionStoreError>>,
}

impl std::fmt::Debug for SessionRecorder {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("SessionRecorder")
            .finish_non_exhaustive()
    }
}

impl SessionRecorder {
    /// Creates a recorder over a shared session and a downstream sink.
    #[must_use]
    pub fn new(session: Arc<Mutex<NativeSession>>, inner: Arc<dyn EventSink>) -> Self {
        Self {
            session,
            inner,
            failure: Mutex::new(None),
        }
    }

    /// Takes the first persistence failure, if any.
    #[must_use]
    pub fn take_failure(&self) -> Option<SessionStoreError> {
        self.failure
            .lock()
            .ok()
            .and_then(|mut failure| failure.take())
    }
}

impl EventSink for SessionRecorder {
    fn emit(&self, event: AgentEvent) {
        if let AgentEvent::MessageEnd { message } = &event {
            let kind = match message.role {
                MessageRole::System => SessionRecordKind::Metadata,
                MessageRole::User => SessionRecordKind::UserMessage,
                MessageRole::Assistant => SessionRecordKind::AssistantMessage,
                MessageRole::Tool => SessionRecordKind::ToolResult,
            };
            let result = match self.session.lock() {
                Ok(mut session) => session.append_message(kind, message.clone()).map(|_| ()),
                Err(_) => Err(SessionStoreError::Io {
                    operation: "lock session recorder".to_owned(),
                    message: "session mutex was poisoned".to_owned(),
                }),
            };
            if let Err(error) = result
                && let Ok(mut failure) = self.failure.lock()
                && failure.is_none()
            {
                *failure = Some(error);
            }
        }
        self.inner.emit(event);
    }
}

/// Result of a run whose messages were committed to a session journal.
#[derive(Debug)]
pub struct PersistentRunResult {
    /// The runtime result.
    pub run: AgentRunResult,
    /// The first persistence failure observed during the run, if any.
    pub persistence_error: Option<SessionStoreError>,
}

impl AgentRuntime<'_> {
    /// Runs one prompt against a persistent session.
    ///
    /// The runtime context is replaced by the session's committed transcript
    /// before the run. A run-start marker is committed before any provider
    /// request, every finished message is committed as it ends, and a
    /// run-finish marker records the terminal outcome. A session that still has
    /// an incomplete run from an earlier process is refused, because the owner
    /// must decide how to settle that unknown outcome first.
    ///
    /// # Errors
    ///
    /// Returns a store error when the session cannot admit the run or the
    /// run-start marker cannot be committed.
    pub async fn run_persistent(
        &mut self,
        session: Arc<Mutex<NativeSession>>,
        prompt: Message,
        sink: Arc<dyn EventSink>,
    ) -> Result<PersistentRunResult, SessionStoreError> {
        {
            let mut guard = session.lock().map_err(|_| SessionStoreError::Io {
                operation: "lock session".to_owned(),
                message: "session mutex was poisoned".to_owned(),
            })?;
            guard.begin_run(Vec::new())?;
            self.context = AgentContext {
                messages: guard.messages().to_vec(),
            };
        }
        let recorder = Arc::new(SessionRecorder::new(Arc::clone(&session), sink));
        let run = self.run(prompt, recorder.clone()).await;
        let finish_payload = match &run.outcome {
            AgentOutcome::Completed => b"completed".to_vec(),
            AgentOutcome::Aborted => b"aborted".to_vec(),
            AgentOutcome::Unknown { .. } => b"unknown".to_vec(),
            AgentOutcome::Failed { code, .. } => format!("failed:{code}").into_bytes(),
        };
        let finish_error = session
            .lock()
            .map_err(|_| SessionStoreError::Io {
                operation: "lock session".to_owned(),
                message: "session mutex was poisoned".to_owned(),
            })
            .and_then(|mut guard| guard.finish_run(finish_payload))
            .err();
        Ok(PersistentRunResult {
            run,
            persistence_error: recorder.take_failure().or(finish_error),
        })
    }
}

/// Copies a provider's terminal reason onto the assistant message.
fn record_stop_reason(assistant: &mut Message, reason: &ProviderStopReason) {
    match reason {
        ProviderStopReason::Stop => assistant.stop_reason = Some(StopReason::Stop),
        ProviderStopReason::ToolUse => assistant.stop_reason = Some(StopReason::ToolUse),
        ProviderStopReason::Length => assistant.stop_reason = Some(StopReason::Length),
        ProviderStopReason::Aborted => assistant.stop_reason = Some(StopReason::Aborted),
        ProviderStopReason::Error { message } => {
            assistant.stop_reason = Some(StopReason::Error);
            assistant.error_message = Some(message.clone());
        }
    }
}

/// A single-agent runtime with explicit provider, tool, and cancellation owners.
pub struct AgentRuntime<'a> {
    providers: &'a dyn ProviderRegistry,
    tools: &'a dyn ToolRegistry,
    config: RuntimeConfig,
    context: AgentContext,
    cancellation: CancellationToken,
}

impl std::fmt::Debug for AgentRuntime<'_> {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("AgentRuntime")
            .field("config", &self.config)
            .field("context", &self.context)
            .field("cancelled", &self.cancellation.is_cancelled())
            .finish_non_exhaustive()
    }
}

impl<'a> AgentRuntime<'a> {
    /// Creates a runtime that borrows provider and tool registries for one process.
    #[must_use]
    pub fn new(
        providers: &'a dyn ProviderRegistry,
        tools: &'a dyn ToolRegistry,
        config: RuntimeConfig,
    ) -> Self {
        Self {
            providers,
            tools,
            config,
            context: AgentContext::default(),
            cancellation: CancellationToken::new(),
        }
    }

    /// Replaces the initial transcript before the first run.
    pub fn set_context(&mut self, context: AgentContext) {
        self.context = context;
    }

    /// Returns a shared cancellation token owned by this runtime.
    #[must_use]
    pub fn cancellation(&self) -> CancellationToken {
        self.cancellation.clone()
    }

    /// Returns the current transcript.
    #[must_use]
    pub fn context(&self) -> &AgentContext {
        &self.context
    }

    /// Runs one prompt and emits lifecycle events synchronously as async work advances.
    pub async fn run(&mut self, prompt: Message, sink: Arc<dyn EventSink>) -> AgentRunResult {
        let run_start = self.context.messages.len();
        self.context.messages.push(prompt.clone());
        sink.emit(AgentEvent::AgentStart);
        sink.emit(AgentEvent::MessageStart {
            message: prompt.clone(),
        });
        sink.emit(AgentEvent::MessageEnd { message: prompt });

        let outcome = match self.run_turns(Arc::clone(&sink)).await {
            Ok(outcome) => outcome,
            Err(error) => self.finish_failure(&error, &*sink),
        };
        sink.emit(AgentEvent::AgentEnd {
            outcome: outcome.clone(),
            messages: self.context.messages[run_start..].to_vec(),
        });
        AgentRunResult {
            messages: self.context.messages.clone(),
            outcome,
        }
    }

    async fn run_turns(&mut self, sink: Arc<dyn EventSink>) -> Result<AgentOutcome, RuntimeError> {
        for turn in 0..self.config.max_turns {
            if self.cancellation.is_cancelled() {
                return Ok(self.finish_aborted(&*sink));
            }
            sink.emit(AgentEvent::TurnStart { turn: turn + 1 });
            let (assistant, reason) = self.request_assistant(&sink).await?;
            if assistant.tool_calls.is_empty() {
                if reason == ProviderStopReason::ToolUse {
                    return Err(RuntimeError::Core(CoreError::InvalidState {
                        message: "provider declared tool use without a tool call".to_owned(),
                    }));
                }
                sink.emit(AgentEvent::TurnEnd {
                    message: assistant,
                    tool_results: Vec::new(),
                });
                return Ok(match reason {
                    ProviderStopReason::Aborted => AgentOutcome::Aborted,
                    ProviderStopReason::Error { message } => AgentOutcome::Failed {
                        code: "provider",
                        message,
                    },
                    ProviderStopReason::Stop
                    | ProviderStopReason::ToolUse
                    | ProviderStopReason::Length => AgentOutcome::Completed,
                });
            }

            let tool_results = self.execute_tools(&assistant, &sink).await?;
            sink.emit(AgentEvent::TurnEnd {
                message: assistant,
                tool_results,
            });
        }
        Err(RuntimeError::TurnLimit {
            max_turns: self.config.max_turns,
        })
    }

    async fn request_assistant(
        &mut self,
        sink: &Arc<dyn EventSink>,
    ) -> Result<(Message, ProviderStopReason), RuntimeError> {
        let provider = self.providers.provider(&self.config.model.provider)?;
        for retry_index in 0..=self.config.max_retries {
            self.cancellation.check()?;
            let request = ProviderRequest {
                model: self.config.model.clone(),
                messages: self.context.messages.clone(),
                tools: self
                    .tools
                    .definitions()
                    .into_iter()
                    .map(|definition| ToolSpec {
                        name: definition.name,
                        description: definition.description,
                    })
                    .collect(),
                cancellation: self.cancellation.clone(),
            };
            match provider.stream(request).await {
                Ok(mut stream) => match self.consume_stream(&mut *stream, &**sink).await {
                    Ok(result) => {
                        if retry_index > 0 {
                            sink.emit(AgentEvent::RetryEnd {
                                attempt: retry_index,
                                succeeded: true,
                            });
                        }
                        return Ok(result);
                    }
                    Err(failure)
                        if failure.is_retryable() && retry_index < self.config.max_retries =>
                    {
                        let attempt = retry_index + 1;
                        sink.emit(AgentEvent::RetryStart { attempt });
                    }
                    Err(failure) => {
                        if retry_index > 0 {
                            sink.emit(AgentEvent::RetryEnd {
                                attempt: retry_index,
                                succeeded: false,
                            });
                        }
                        return Err(failure.error);
                    }
                },
                Err(error) if error.is_retryable() && retry_index < self.config.max_retries => {
                    let attempt = retry_index + 1;
                    sink.emit(AgentEvent::RetryStart { attempt });
                }
                Err(error) => {
                    if retry_index > 0 {
                        sink.emit(AgentEvent::RetryEnd {
                            attempt: retry_index,
                            succeeded: false,
                        });
                    }
                    return Err(error.into());
                }
            }
        }
        Err(RuntimeError::UnterminatedProviderStream)
    }

    /// Adds the assistant message to the transcript and announces it, once.
    ///
    /// Returns `true` so callers can record that the message has started.
    fn start_message(&mut self, started: bool, assistant: &Message, sink: &dyn EventSink) -> bool {
        if !started {
            self.context.messages.push(assistant.clone());
            sink.emit(AgentEvent::MessageStart {
                message: assistant.clone(),
            });
        }
        true
    }

    /// Reads the next provider event, tagging any failure with whether output already started.
    async fn next_provider_event(
        &self,
        stream: &mut dyn nyan_coding_agent_provider::ProviderStream,
        started: bool,
    ) -> Result<ProviderStreamEvent, StreamAttemptError> {
        self.cancellation
            .check()
            .map_err(|error| StreamAttemptError {
                error: error.into(),
                emitted: started,
            })?;
        match stream.next().await {
            Ok(Some(event)) => Ok(event),
            Ok(None) => Err(StreamAttemptError {
                error: RuntimeError::UnterminatedProviderStream,
                emitted: started,
            }),
            Err(error) => Err(StreamAttemptError {
                error: RuntimeError::Provider(error),
                emitted: started,
            }),
        }
    }

    async fn consume_stream(
        &mut self,
        stream: &mut dyn nyan_coding_agent_provider::ProviderStream,
        sink: &dyn EventSink,
    ) -> Result<(Message, ProviderStopReason), StreamAttemptError> {
        let mut assistant = Message::text(MessageRole::Assistant, "");
        assistant.provider = Some(self.config.model.provider.clone());
        assistant.model = Some(self.config.model.model.clone());
        let mut started = false;
        let mut blocks = 0_usize;
        let mut text_index: Option<usize> = None;
        loop {
            let event = self.next_provider_event(stream, started).await?;
            match event {
                ProviderStreamEvent::TextDelta { text } => {
                    started = self.start_message(started, &assistant, sink);
                    let content_index = if let Some(index) = text_index {
                        index
                    } else {
                        let index = blocks;
                        blocks += 1;
                        text_index = Some(index);
                        sink.emit(AgentEvent::MessageUpdate {
                            message: assistant.clone(),
                            event: AssistantEvent::TextStart {
                                content_index: index,
                            },
                        });
                        index
                    };
                    assistant.text.push_str(&text);
                    self.replace_last_message(&assistant);
                    sink.emit(AgentEvent::MessageUpdate {
                        message: assistant.clone(),
                        event: AssistantEvent::TextDelta {
                            content_index,
                            delta: text,
                        },
                    });
                }
                ProviderStreamEvent::ToolCall(call) => {
                    started = self.start_message(started, &assistant, sink);
                    let id = ToolCallId::new(call.id).map_err(|error| StreamAttemptError {
                        error: error.into(),
                        emitted: started,
                    })?;
                    let content_index = blocks;
                    blocks += 1;
                    let tool_call = ToolCall {
                        id,
                        name: call.name,
                        arguments: call.arguments,
                    };
                    sink.emit(AgentEvent::MessageUpdate {
                        message: assistant.clone(),
                        event: AssistantEvent::ToolCallStart {
                            content_index,
                            id: tool_call.id.clone(),
                            name: tool_call.name.clone(),
                        },
                    });
                    assistant.tool_calls.push(tool_call.clone());
                    self.replace_last_message(&assistant);
                    sink.emit(AgentEvent::MessageUpdate {
                        message: assistant.clone(),
                        event: AssistantEvent::ToolCallEnd {
                            content_index,
                            tool_call,
                        },
                    });
                }
                ProviderStreamEvent::Usage(usage) => assistant.usage = Some(usage),
                ProviderStreamEvent::Finished { reason } => {
                    record_stop_reason(&mut assistant, &reason);
                    self.start_message(started, &assistant, sink);
                    if let Some(content_index) = text_index {
                        sink.emit(AgentEvent::MessageUpdate {
                            message: assistant.clone(),
                            event: AssistantEvent::TextEnd {
                                content_index,
                                content: assistant.text.clone(),
                            },
                        });
                    }
                    self.replace_last_message(&assistant);
                    sink.emit(AgentEvent::MessageEnd {
                        message: assistant.clone(),
                    });
                    return Ok((assistant, reason));
                }
            }
        }
    }

    async fn execute_tools(
        &mut self,
        assistant: &Message,
        sink: &Arc<dyn EventSink>,
    ) -> Result<Vec<Message>, RuntimeError> {
        match self.config.tool_execution {
            ToolExecutionMode::Sequential => self.execute_tools_sequential(assistant, sink).await,
            ToolExecutionMode::Parallel => self.execute_tools_parallel(assistant, sink).await,
        }
    }

    async fn execute_tools_sequential(
        &mut self,
        assistant: &Message,
        sink: &Arc<dyn EventSink>,
    ) -> Result<Vec<Message>, RuntimeError> {
        let mut results = Vec::with_capacity(assistant.tool_calls.len());
        for call in &assistant.tool_calls {
            self.cancellation.check()?;
            sink.emit(AgentEvent::ToolExecutionStart {
                call_id: call.id.clone(),
                tool_name: call.name.clone(),
                arguments: call.arguments.clone(),
            });
            let (text, is_error) = match self.tools.tool(&call.name) {
                Some(tool) => {
                    let accepting_updates = Arc::new(Mutex::new(true));
                    let update_sink: ToolUpdateSink = {
                        let accepting_updates = Arc::clone(&accepting_updates);
                        let sink = Arc::clone(sink);
                        let call_id = call.id.clone();
                        let tool_name = call.name.clone();
                        Arc::new(move |partial_result| {
                            if let Ok(active) = accepting_updates.lock()
                                && *active
                            {
                                sink.emit(AgentEvent::ToolExecutionUpdate {
                                    call_id: call_id.clone(),
                                    tool_name: tool_name.clone(),
                                    partial_result,
                                });
                            }
                        })
                    };
                    let execution = tool
                        .execute(
                            call.arguments.clone(),
                            ExecutionContext::new(
                                self.config.cwd.clone(),
                                self.cancellation.clone(),
                            )
                            .with_update_sink(update_sink),
                        )
                        .await;
                    if let Ok(mut active) = accepting_updates.lock() {
                        *active = false;
                    }
                    match execution {
                        Ok(result) => (result.text, result.is_error),
                        Err(ToolError::Cancelled) => {
                            let result = Message::tool_result(
                                call.id.clone(),
                                &call.name,
                                "tool execution cancelled",
                                true,
                            );
                            self.emit_tool_result(call, result, &**sink);
                            return Err(RuntimeError::Core(CoreError::Cancelled));
                        }
                        Err(ToolError::UnknownOutcome { operation, message }) => {
                            let result = Message::tool_result(
                                call.id.clone(),
                                &call.name,
                                format!("unknown outcome for {operation}: {message}"),
                                true,
                            );
                            self.emit_tool_result(call, result, &**sink);
                            return Err(RuntimeError::UnknownOutcome { operation, message });
                        }
                        Err(error) => (error.to_string(), true),
                    }
                }
                None => (format!("unknown tool: {}", call.name), true),
            };
            let result = Message::tool_result(call.id.clone(), &call.name, text, is_error);
            self.emit_tool_result(call, result.clone(), &**sink);
            results.push(result);
            if self.cancellation.is_cancelled() {
                return Err(RuntimeError::Core(CoreError::Cancelled));
            }
        }
        Ok(results)
    }

    async fn execute_tools_parallel(
        &mut self,
        assistant: &Message,
        sink: &Arc<dyn EventSink>,
    ) -> Result<Vec<Message>, RuntimeError> {
        let mut pending = Vec::with_capacity(assistant.tool_calls.len());
        for call in &assistant.tool_calls {
            self.cancellation.check()?;
            sink.emit(AgentEvent::ToolExecutionStart {
                call_id: call.id.clone(),
                tool_name: call.name.clone(),
                arguments: call.arguments.clone(),
            });
            pending.push(PendingTool {
                call: call.clone(),
                future: self.prepare_tool_future(call, sink),
            });
        }

        let completed = JoinToolFutures {
            results: (0..pending.len()).map(|_| None).collect(),
            pending: pending.into_iter().map(Some).collect(),
        }
        .await;
        let mut results = Vec::with_capacity(completed.len());
        for (call, execution) in completed {
            let result = self.finalize_tool_execution(&call, execution, &**sink)?;
            results.push(result);
            if self.cancellation.is_cancelled() {
                return Err(RuntimeError::Core(CoreError::Cancelled));
            }
        }
        Ok(results)
    }

    fn prepare_tool_future(
        &self,
        call: &ToolCall,
        sink: &Arc<dyn EventSink>,
    ) -> BoxFuture<Result<ToolResult, ToolError>> {
        let Some(tool) = self.tools.tool(&call.name) else {
            let name = call.name.clone();
            return Box::pin(async move { Err(ToolError::UnknownTool { name }) });
        };
        let accepting_updates = Arc::new(Mutex::new(true));
        let update_sink: ToolUpdateSink = {
            let accepting_updates = Arc::clone(&accepting_updates);
            let sink = Arc::clone(sink);
            let call_id = call.id.clone();
            let tool_name = call.name.clone();
            Arc::new(move |partial_result| {
                if let Ok(active) = accepting_updates.lock()
                    && *active
                {
                    sink.emit(AgentEvent::ToolExecutionUpdate {
                        call_id: call_id.clone(),
                        tool_name: tool_name.clone(),
                        partial_result,
                    });
                }
            })
        };
        let execution = tool.execute(
            call.arguments.clone(),
            ExecutionContext::new(self.config.cwd.clone(), self.cancellation.clone())
                .with_update_sink(update_sink),
        );
        Box::pin(async move {
            let result = execution.await;
            if let Ok(mut active) = accepting_updates.lock() {
                *active = false;
            }
            result
        })
    }

    fn finalize_tool_execution(
        &mut self,
        call: &ToolCall,
        execution: Result<ToolResult, ToolError>,
        sink: &dyn EventSink,
    ) -> Result<Message, RuntimeError> {
        match execution {
            Ok(result) => {
                let result =
                    Message::tool_result(call.id.clone(), &call.name, result.text, result.is_error);
                self.emit_tool_result(call, result.clone(), sink);
                Ok(result)
            }
            Err(ToolError::Cancelled) => {
                let result = Message::tool_result(
                    call.id.clone(),
                    &call.name,
                    "tool execution cancelled",
                    true,
                );
                self.emit_tool_result(call, result, sink);
                Err(RuntimeError::Core(CoreError::Cancelled))
            }
            Err(ToolError::UnknownOutcome { operation, message }) => {
                let result = Message::tool_result(
                    call.id.clone(),
                    &call.name,
                    format!("unknown outcome for {operation}: {message}"),
                    true,
                );
                self.emit_tool_result(call, result, sink);
                Err(RuntimeError::UnknownOutcome { operation, message })
            }
            Err(error) => {
                let result =
                    Message::tool_result(call.id.clone(), &call.name, error.to_string(), true);
                self.emit_tool_result(call, result.clone(), sink);
                Ok(result)
            }
        }
    }

    fn emit_tool_result(&mut self, call: &ToolCall, result: Message, sink: &dyn EventSink) {
        self.context.messages.push(result.clone());
        sink.emit(AgentEvent::ToolExecutionEnd {
            call_id: call.id.clone(),
            tool_name: call.name.clone(),
            result: result.clone(),
        });
        sink.emit(AgentEvent::MessageStart {
            message: result.clone(),
        });
        sink.emit(AgentEvent::MessageEnd { message: result });
    }

    fn replace_last_message(&mut self, message: &Message) {
        if let Some(last) = self.context.messages.last_mut() {
            *last = message.clone();
        }
    }

    fn finish_aborted(&mut self, sink: &dyn EventSink) -> AgentOutcome {
        let mut message = Message::text(MessageRole::Assistant, "operation cancelled");
        message.stop_reason = Some(StopReason::Aborted);
        message.error_message = Some("operation cancelled".to_owned());
        self.context.messages.push(message.clone());
        sink.emit(AgentEvent::MessageStart {
            message: message.clone(),
        });
        sink.emit(AgentEvent::MessageEnd {
            message: message.clone(),
        });
        sink.emit(AgentEvent::TurnEnd {
            message,
            tool_results: Vec::new(),
        });
        AgentOutcome::Aborted
    }

    fn finish_failure(&mut self, error: &RuntimeError, sink: &dyn EventSink) -> AgentOutcome {
        if error.is_cancelled() || self.cancellation.is_cancelled() {
            return self.finish_aborted(sink);
        }
        let mut message = Message::text(MessageRole::Assistant, error.to_string());
        message.stop_reason = Some(StopReason::Error);
        message.error_message = Some(error.to_string());
        self.context.messages.push(message.clone());
        sink.emit(AgentEvent::MessageStart {
            message: message.clone(),
        });
        sink.emit(AgentEvent::MessageEnd {
            message: message.clone(),
        });
        sink.emit(AgentEvent::TurnEnd {
            message,
            tool_results: Vec::new(),
        });
        match error {
            RuntimeError::UnknownOutcome { operation, message } => AgentOutcome::Unknown {
                operation: operation.clone(),
                message: message.clone(),
            },
            _ => AgentOutcome::Failed {
                code: error.code(),
                message: error.to_string(),
            },
        }
    }
}

