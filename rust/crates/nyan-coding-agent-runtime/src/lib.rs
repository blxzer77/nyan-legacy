/// Events emitted in deterministic order by one agent run.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum AgentEvent {
    /// The run has started.
    AgentStart,
    /// The run has reached a terminal outcome.
    AgentEnd {
        /// Terminal run outcome.
        outcome: AgentOutcome,
        /// Messages generated by this run, starting with the prompt.
        messages: Vec<Message>,
    },
    /// A provider turn has started.
    TurnStart {
        /// One-based turn number.
        turn: usize,
    },
    /// A message has begun.
    MessageStart {
        /// Initial message value.
        message: Message,
    },
    /// A streaming message changed.
    MessageUpdate {
        /// Current message value.
        message: Message,
        /// The content-block change that caused this update.
        event: AssistantEvent,
    },
    /// A message has finished.
    MessageEnd {
        /// Final message value.
        message: Message,
    },
    /// A retryable provider failure will be retried after a delay.
    RetryStart {
        /// One-based retry number.
        attempt: usize,
        /// The most retries that will be made.
        max_attempts: usize,
        /// How long the runtime waits before trying again.
        delay_ms: u64,
        /// Why the previous attempt failed.
        error_message: String,
    },
    /// A provider retry attempt has ended.
    RetryEnd {
        /// Number of retries made so far.
        attempt: usize,
        /// Whether the retry produced a complete stream.
        succeeded: bool,
        /// Why the retries stopped, when they failed.
        final_error: Option<String>,
    },
    /// Queued steering and follow-up messages changed.
    QueueUpdate {
        /// Messages waiting to be inserted before the next provider request.
        steering: Vec<Message>,
        /// Messages waiting until the current agent turn settles.
        follow_up: Vec<Message>,
    },
    /// A tool call has begun.
    ToolExecutionStart {
        /// Provider call id.
        call_id: ToolCallId,
        /// Registered tool name.
        tool_name: String,
        /// Opaque JSON arguments.
        arguments: String,
    },
    /// A tool has emitted a partial result.
    ToolExecutionUpdate {
        /// Provider call id.
        call_id: ToolCallId,
        /// Registered tool name.
        tool_name: String,
        /// Opaque JSON arguments of the call.
        arguments: String,
        /// Partial result.
        partial_result: ToolResult,
    },
    /// A tool call has finished.
    ToolExecutionEnd {
        /// Provider call id.
        call_id: ToolCallId,
        /// Registered tool name.
        tool_name: String,
        /// Model-facing result.
        result: Message,
        /// How long the tool ran, measured with a monotonic clock; absent when it never ran.
        duration_ms: Option<u64>,
    },
    /// A turn has finished, including its tool results.
    TurnEnd {
        /// Assistant message for the turn.
        message: Message,
        /// Tool result messages generated by the turn.
        tool_results: Vec<Message>,
    },
}

/// One content-block change inside a streaming assistant message.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum AssistantEvent {
    /// A text block started.
    TextStart {
        /// Index of the block in the message content.
        content_index: usize,
    },
    /// Text was appended to a block.
    TextDelta {
        /// Index of the block in the message content.
        content_index: usize,
        /// The appended text.
        delta: String,
    },
    /// A text block ended with its authoritative content.
    TextEnd {
        /// Index of the block in the message content.
        content_index: usize,
        /// The complete block text.
        content: String,
    },
    /// A thinking block started.
    ThinkingStart {
        /// Index of the block in the message content.
        content_index: usize,
    },
    /// Thinking text was appended to a block.
    ThinkingDelta {
        /// Index of the block in the message content.
        content_index: usize,
        /// The appended thinking text.
        delta: String,
    },
    /// A thinking block ended with its authoritative content.
    ThinkingEnd {
        /// Index of the block in the message content.
        content_index: usize,
        /// The complete block text; empty for a redacted block.
        content: String,
    },
    /// A tool-call block started.
    ToolCallStart {
        /// Index of the block in the message content.
        content_index: usize,
        /// Provider call id.
        id: ToolCallId,
        /// Tool name.
        name: String,
    },
    /// A tool-call block ended with the complete call.
    ToolCallEnd {
        /// Index of the block in the message content.
        content_index: usize,
        /// The complete tool call.
        tool_call: ToolCall,
    },
}

/// Terminal state of a run.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum AgentOutcome {
    /// The provider completed without more tool calls.
    Completed,
    /// The owning process requested cancellation before an external effect started.
    Aborted,
    /// An external effect started but its final outcome could not be proven.
    Unknown {
        /// The operation whose outcome is not known.
        operation: String,
        /// Diagnostic explaining the uncertainty.
        message: String,
    },
    /// The run stopped on a stable runtime error.
    Failed {
        /// Stable error category.
        code: &'static str,
        /// User- or model-facing diagnostic.
        message: String,
    },
}

/// Final result and transcript returned by one run.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct AgentRunResult {
    /// Messages appended during the run, including the prompt.
    pub messages: Vec<Message>,
    /// Stable terminal outcome.
    pub outcome: AgentOutcome,
}

/// Tool scheduling policy for one assistant message.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ToolExecutionMode {
    /// Execute tool calls in provider order.
    Sequential,
    /// Start all tool calls in one assistant message and await them concurrently.
    Parallel,
}

/// How queued messages are consumed when the runtime reaches a safe turn boundary.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QueueMode {
    /// Consume one queued message and leave the rest for the next turn.
    OneAtATime,
    /// Consume every queued message in one turn boundary.
    All,
}

/// A read-only snapshot of the steering and follow-up queues.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct QueueSnapshot {
    /// Messages inserted before the next provider request.
    pub steering: Vec<Message>,
    /// Messages submitted after the current agent turn settles.
    pub follow_up: Vec<Message>,
}

#[derive(Debug, Default)]
struct QueueState {
    steering: Mutex<VecDeque<Message>>,
    follow_up: Mutex<VecDeque<Message>>,
}

impl QueueState {
    fn snapshot(&self) -> QueueSnapshot {
        QueueSnapshot {
            steering: self
                .steering
                .lock()
                .expect("steering queue lock")
                .iter()
                .cloned()
                .collect(),
            follow_up: self
                .follow_up
                .lock()
                .expect("follow-up queue lock")
                .iter()
                .cloned()
                .collect(),
        }
    }

    fn push_steering(&self, message: Message) {
        self.steering
            .lock()
            .expect("steering queue lock")
            .push_back(message);
    }

    fn push_follow_up(&self, message: Message) {
        self.follow_up
            .lock()
            .expect("follow-up queue lock")
            .push_back(message);
    }

    fn take_steering(&self, mode: QueueMode) -> Vec<Message> {
        take_queue(&self.steering, mode)
    }

    fn take_follow_up(&self, mode: QueueMode) -> Vec<Message> {
        take_queue(&self.follow_up, mode)
    }

    fn clear(&self) -> QueueSnapshot {
        let snapshot = self.snapshot();
        self.steering.lock().expect("steering queue lock").clear();
        self.follow_up.lock().expect("follow-up queue lock").clear();
        snapshot
    }
}

fn take_queue(queue: &Mutex<VecDeque<Message>>, mode: QueueMode) -> Vec<Message> {
    let mut queue = queue.lock().expect("message queue lock");
    match mode {
        QueueMode::OneAtATime => queue.pop_front().into_iter().collect(),
        QueueMode::All => queue.drain(..).collect(),
    }
}

/// Control handle for queues and cancellation owned by an agent runtime.
#[derive(Clone, Debug)]
pub struct AgentControl {
    queues: Arc<QueueState>,
    cancellation: CancellationToken,
}

impl AgentControl {
    /// Queues a message to be inserted before the next provider request.
    pub fn steer(&self, message: Message) {
        self.queues.push_steering(message);
    }

    /// Queues a message to be submitted after the current turn settles.
    pub fn follow_up(&self, message: Message) {
        self.queues.push_follow_up(message);
    }

    /// Returns the current queue contents without removing them.
    #[must_use]
    pub fn snapshot(&self) -> QueueSnapshot {
        self.queues.snapshot()
    }

    /// Clears both queues and returns what was removed.
    #[must_use]
    pub fn clear_queue(&self) -> QueueSnapshot {
        self.queues.clear()
    }

    /// Requests cancellation of the owning runtime.
    pub fn abort(&self) {
        self.cancellation.cancel();
    }
}

/// Waits for a duration, returning early when the token is cancelled.
///
/// The runtime does not choose an executor, so whoever builds it supplies the timer.
#[derive(Clone)]
pub struct RetrySleep(Arc<dyn Fn(Duration, CancellationToken) -> BoxFuture<()> + Send + Sync>);

impl RetrySleep {
    /// Wraps a sleep function.
    pub fn new(
        sleep: impl Fn(Duration, CancellationToken) -> BoxFuture<()> + Send + Sync + 'static,
    ) -> Self {
        Self(Arc::new(sleep))
    }
}

impl std::fmt::Debug for RetrySleep {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> std::fmt::Result {
        formatter.write_str("RetrySleep")
    }
}

impl PartialEq for RetrySleep {
    fn eq(&self, other: &Self) -> bool {
        Arc::ptr_eq(&self.0, &other.0)
    }
}

impl Eq for RetrySleep {}

/// Configuration for one runtime instance.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct RuntimeConfig {
    /// Selected provider and model.
    pub model: ProviderModel,
    /// Working directory passed to tools.
    pub cwd: PathBuf,
    /// Maximum assistant turns, including the first request.
    pub max_turns: usize,
    /// Maximum fresh provider attempts after a retryable failure.
    pub max_retries: usize,
    /// The wait before the first retry; each later retry waits twice as long.
    pub retry_base_delay: Duration,
    /// The longest wait before one retry.
    pub retry_max_delay: Duration,
    /// How the runtime waits between retries; without one it retries at once.
    pub retry_sleep: Option<RetrySleep>,
    /// Tool scheduling policy.
    pub tool_execution: ToolExecutionMode,
    /// Steering queue consumption policy.
    pub steering_mode: QueueMode,
    /// Follow-up queue consumption policy.
    pub follow_up_mode: QueueMode,
    /// The conversation id sent with every provider request.
    pub session_id: Option<String>,
    /// Optional provider request controls.
    pub request_options: ProviderRequestOptions,
}

impl RuntimeConfig {
    /// Creates the default configuration for a terminal run.
    #[must_use]
    pub fn new(model: ProviderModel, cwd: impl Into<PathBuf>) -> Self {
        Self {
            model,
            cwd: cwd.into(),
            max_turns: 64,
            max_retries: 3,
            retry_base_delay: Duration::from_secs(2),
            retry_max_delay: Duration::from_secs(60),
            retry_sleep: None,
            tool_execution: ToolExecutionMode::Parallel,
            steering_mode: QueueMode::OneAtATime,
            follow_up_mode: QueueMode::OneAtATime,
            session_id: None,
            request_options: ProviderRequestOptions::default(),
        }
    }
}

